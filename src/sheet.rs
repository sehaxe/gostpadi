//! Лист документации: формат А4, поля, вписывание раскладки.
//!
//! ГОСТ 19.701-90 формат листа и поля не задаёт — это делает ЕСКД:
//! лист А4 210×297 мм с полями документации. Модуль владеет всей
//! геометрией страницы: размером листа, полями, решением «влезает ли
//! содержимое» и положением содержимого в текстовой зоне.
//!
//! Порезка схемы ([`crate::layout::split_scheme`]) и рендер
//! ([`crate::generate::render_svg_at`]) спрашивают его, а не считают
//! сами. Раньше «влезает ли» было двумя формулами в двух модулях
//! (высота против обеих осей, с порогом и без), а `page_pad`
//! вычитался из листа дважды: уже запечённый в `Layout::bounds`
//! и ещё раз в `fit_scale` с `split_scheme`.
//!
//! Лист выбирается один на всю пачку схем, а не на каждый файл:
//! ГОСТ 19.701-90 п. 4.1.3 требует, чтобы символы были одного
//! размера, и страницы лабы тоже обязаны совпадать.

/// пункт в миллиметре.
const MM: f64 = 72.0 / 25.4;

/// Лист: размер и поля в пунктах. `Layout::bounds` — точный габарит
/// содержимого без полей; поля принадлежат листу, а не раскладке.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct Sheet {
    pub w: f64,
    pub h: f64,
    pub m_l: f64,
    pub m_r: f64,
    pub m_t: f64,
    pub m_b: f64,
}

impl Sheet {
    /// А4 книжная, 210×297 мм. Поля документации ЕСКД: левое 30 мм под
    /// подшивку, правое 10, верхнее и нижнее по 20. Текстовая зона
    /// 170×257 мм.
    pub const A4: Sheet = Sheet {
        w: 210.0 * MM,
        h: 297.0 * MM,
        m_l: 30.0 * MM,
        m_r: 10.0 * MM,
        m_t: 20.0 * MM,
        m_b: 20.0 * MM,
    };

    /// Тот же лист в альбомной ориентации: 297×210 мм, поля повёрнуты
    /// вместе с листом, текстовая зона 257×170 мм.
    pub const A4_LANDSCAPE: Sheet = Sheet {
        w: 297.0 * MM,
        h: 210.0 * MM,
        m_l: 20.0 * MM,
        m_r: 20.0 * MM,
        m_t: 30.0 * MM,
        m_b: 30.0 * MM,
    };

    /// Ширина текстовой зоны (без полей).
    pub fn text_w(&self) -> f64 {
        self.w - self.m_l - self.m_r
    }

    /// Высота текстовой зоны (без полей).
    pub fn text_h(&self) -> f64 {
        self.h - self.m_t - self.m_b
    }

    /// Масштаб вписывания содержимого `w × h` в текстовую зону.
    /// Не больше 1: мелкие схемы рисуются в натуральную величину.
    pub fn scale_for(&self, w: f64, h: f64) -> f64 {
        if w <= 0.0 || h <= 0.0 {
            return 1.0;
        }
        1.0_f64.min(self.text_w() / w).min(self.text_h() / h)
    }

    /// Вписывается ли содержимое высотой `h`, не опуская масштаб
    /// вписывания ниже `floor`. Это и есть вопрос порезки: резать
    /// имеет смысл, когда лист без этого стал бы нечитаемым.
    pub fn fits_height(&self, h: f64, floor: f64) -> bool {
        h * floor <= self.text_h()
    }

    /// Смещение содержимого в текстовой зоне при масштабе `s`.
    ///
    /// По горизонтали центрируется **главная ось схемы** (точка x = 0 в
    /// координатах раскладки), а не габарит: ось — позвоночник
    /// блок-схемы, и по габариту она уезжала на половину асимметрии.
    /// Схема с широкой «да»-веткой и узкой «нет» сдвигала ствол вправо
    /// на 107 pt от центра листа. Ось центрируется всегда, но если при
    /// этом содержимое вышло бы за поля, сдвиг ужимается до ближайшей
    /// допустимой позиции — выход за поля хуже смещения.
    ///
    /// По вертикали габарит центрируется: «ось» тут есть только сверху
    /// (блок «начало»), и симметрия сверху и снизу читается спокойнее.
    ///
    /// `bounds` — точный габарит содержимого в координатах раскладки.
    pub fn origin(&self, bounds: (f64, f64, f64, f64), s: f64) -> (f64, f64) {
        let (minx, miny, w, h) = bounds;
        // допустимый сдвиг: содержимое целиком внутри текстовой зоны
        let lo = self.m_l - minx * s;
        let hi = self.m_l + self.text_w() - (minx + w) * s;
        let want = self.m_l + self.text_w() / 2.0;
        let x = if lo <= hi {
            want.clamp(lo, hi)
        } else {
            // содержимое шире зоны даже при полном сжатии: прижимаем
            // к левому полю, иначе уедет в минус
            lo.min(hi)
        };
        (x, self.m_t + (self.text_h() - h * s) / 2.0 - miny * s)
    }
}

impl Default for Sheet {
    fn default() -> Self {
        Sheet::A4
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    const TOL: f64 = 1e-9;

    /// Лист — это А4: 210×297 мм, а не «468×700 pt». Раньше в Style
    /// стояли числа, не имевшие отношения к формату.
    #[test]
    fn a4_is_210x297_mm() {
        assert!((Sheet::A4.w / MM - 210.0).abs() < TOL);
        assert!((Sheet::A4.h / MM - 297.0).abs() < TOL);
    }

    /// Поля ЕСКД: 30/10/20/20 мм -> текстовая зона 170×257 мм.
    #[test]
    fn text_area_is_170x257_mm() {
        assert!((Sheet::A4.text_w() / MM - 170.0).abs() < 1e-6);
        assert!((Sheet::A4.text_h() / MM - 257.0).abs() < 1e-6);
    }

    #[test]
    fn landscape_is_rotated_a4() {
        let p = Sheet::A4;
        let l = Sheet::A4_LANDSCAPE;
        assert!((l.w - p.h).abs() < TOL);
        assert!((l.h - p.w).abs() < TOL);
        // поля повёрнуты вместе с листом
        assert!((l.m_l - p.m_t).abs() < TOL);
        assert!((l.m_t - p.m_l).abs() < TOL);
    }

    /// Мелкая схема не увеличивается, крупная сжимается по обеим осям.
    #[test]
    fn scale_never_exceeds_one_and_respects_both_axes() {
        let s = Sheet::A4;
        assert_eq!(s.scale_for(100.0, 100.0), 1.0, "мелкое — 1:1");
        let wide = s.scale_for(s.text_w() * 2.0, 10.0);
        assert!((wide - 0.5).abs() < 1e-9, "широкое жмёт по ширине");
        let tall = s.scale_for(10.0, s.text_h() * 4.0);
        assert!((tall - 0.25).abs() < 1e-9, "высокое жмёт по высоте");
    }

    /// Содержимое всегда внутри текстовой зоны, поля не нарушены.
    /// Проверяем на нескольких габаритах: и влезающих, и сжатых.
    #[test]
    fn content_never_escapes_margins() {
        let s = Sheet::A4;
        for (w, h) in [
            (100.0, 100.0),
            (s.text_w() * 1.7, s.text_h() * 2.3),
            (s.text_w() * 0.4, 300.0),
        ] {
            let bounds = (-40.0, -17.0, w, h);
            let sc = s.scale_for(w, h);
            let (tx, ty) = s.origin(bounds, sc);
            let x0 = tx + bounds.0 * sc;
            let y0 = ty + bounds.1 * sc;
            let x1 = x0 + w * sc;
            let y1 = y0 + h * sc;
            assert!(x0 >= s.m_l - 1e-6, "левое поле: {x0} < {}", s.m_l);
            assert!(y0 >= s.m_t - 1e-6, "верхнее поле: {y0} < {}", s.m_t);
            assert!(x1 <= s.w - s.m_r + 1e-6, "правое поле: {x1}");
            assert!(y1 <= s.h - s.m_b + 1e-6, "нижнее поле: {y1}");
        }
    }

    /// Ключевой инвариант модуля: «влезает ли» в порезке и масштаб
    /// вписывания при рендере — один и тот же вопрос, и ответы
    /// совпадают. Раньше это были две несогласованные формулы в двух
    /// модулях: split считал по высоте с одним page_pad, fit_scale —
    /// по обеим осям с другим.
    #[test]
    fn fits_height_agrees_with_scale_for() {
        let s = Sheet::A4;
        for floor in [0.5, 0.7, 0.9] {
            for mul in [0.3, 0.9, 1.2, 1.5, 3.0] {
                let h = s.text_h() * mul;
                let w = s.text_w() * 0.5; // ширина не ограничивает
                assert_eq!(
                    s.fits_height(h, floor),
                    s.scale_for(w, h) >= floor,
                    "floor={floor} mul={mul}: порезка и рендер разошлись"
                );
            }
        }
    }

    /// Узкая, но очень высокая схема: порезка режет по высоте, вписывание
    /// считает по обеим осям — потому порезка спрашивает лист, а не
    /// прикидывает масштаб сам.
    #[test]
    fn narrow_tall_splits_on_height() {
        let s = Sheet::A4;
        let h = s.text_h() * 2.5;
        assert!(!s.fits_height(h, 0.7), "высокое режем");
        // вписывание сжало бы до 0.4 — нечитаемо
        assert!(s.scale_for(50.0, h) < 0.7);
    }

    /// Вырожденный габарит не делит на ноль.
    #[test]
    fn degenerate_bounds_do_not_panic() {
        assert_eq!(Sheet::A4.scale_for(0.0, 0.0), 1.0);
        assert_eq!(Sheet::A4.scale_for(0.0, 100.0), 1.0);
    }
}
